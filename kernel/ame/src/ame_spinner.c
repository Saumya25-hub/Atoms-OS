void AME_Spinner_Init(AME_Spinner* sp, int cx, int cy, int radius, int num_dots) {
    if (!sp) return;
    sp->center_x = cx;
    sp->center_y = cy;
    sp->radius = (radius > 0) ? radius : 18;
    sp->dot_radius = 3;
    sp->num_dots = (num_dots > 0) ? num_dots : 12;
    if (sp->num_dots > 12) sp->num_dots = 12;
    sp->color = 0x00FFFFFF;
    sp->alpha = 255;
    sp->elapsed_ms = 0;
    sp->speed_scale = 1.0f;
    sp->base_angle = 0;
    sp->active = true;
}

void AME_Spinner_SetPosition(AME_Spinner* sp, int cx, int cy) {
    if (sp) {
        sp->center_x = cx;
        sp->center_y = cy;
    }
}

void AME_Spinner_SetSpeed(AME_Spinner* sp, float speed_scale) {
    if (sp && speed_scale > 0.0f) {
        sp->speed_scale = speed_scale;
    }
}

void AME_Spinner_SetAlpha(AME_Spinner* sp, uint8_t alpha) {
    if (sp) sp->alpha = alpha;
}

void AME_Spinner_Update(AME_Spinner* sp, uint64_t delta_ms) {
    if (!sp || !sp->active) return;
    sp->elapsed_ms += delta_ms;

    /* Base rotation: 360 deg per 1400ms */
    uint64_t effective_ms = (uint64_t)((float)sp->elapsed_ms * sp->speed_scale);
    sp->base_angle = (uint32_t)((effective_ms * 360ULL) / 1400ULL) % 360;
}

static void draw_filled_circle(uint32_t* fb, uint32_t fb_w, uint32_t fb_h, uint32_t stride_pixels, int cx, int cy, int r, uint32_t color) {
    int r2 = r * r;
    for (int dy = -r; dy <= r; dy++) {
        int py = cy + dy;
        if (py < 0 || py >= (int)fb_h) continue;
        int dy2 = dy * dy;
        for (int dx = -r; dx <= r; dx++) {
            int px = cx + dx;
            if (px < 0 || px >= (int)fb_w) continue;
            if (dx * dx + dy2 <= r2) {
                fb[py * stride_pixels + px] = color;
            }
        }
    }
}

void AME_Spinner_Render(const AME_Spinner* sp, uint32_t* framebuffer, uint32_t fb_width, uint32_t fb_height, uint32_t fb_stride) {
    (void)sp; (void)framebuffer; (void)fb_width; (void)fb_height; (void)fb_stride;
}

AME_Spinner* AME_GetBootSpinner(void) {
    if (!g_boot_spinner_inited) {
        AME_Spinner_Init(&g_boot_spinner_instance, 0, 0, 18, 12);
        g_boot_spinner_inited = true;
    }
    return &g_boot_spinner_instance;
}
